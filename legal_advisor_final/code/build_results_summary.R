#!/usr/bin/env Rscript
# Keep numerical prose and the displayed tables at the same published precision.
args <- grep("^--file=",commandArgs(trailingOnly=FALSE),value=TRUE)
root <- normalizePath(file.path(dirname(sub("^--file=","",args[1])),".."))
suppressPackageStartupMessages(library(data.table))
tables <- file.path(root,"output","tables")
rows <- list()
values <- function(file,pattern,occurrence=1L) {
  text <- readLines(file.path(tables,file),warn=FALSE)
  line <- text[grepl(pattern,text,fixed=TRUE) & grepl("&",text,fixed=TRUE)][occurrence]
  if(is.na(line)) stop("Missing result row: ",file," ",pattern)
  cells <- strsplit(line,"&",fixed=TRUE)[[1]][-1]
  vapply(cells,function(cell) {
    match <- regexpr("[-+]?[0-9]+[.][0-9]+",cell)
    if(match[1]<0L) return(NA_real_)
    as.numeric(regmatches(cell,match))
  },numeric(1))
}
add <- function(name,value,source,unit="coefficient") rows[[length(rows)+1L]] <<- data.table(name=name,value=value,source=source,unit=unit)
x <- values("city_year_cs_twfe_main_table.tex","Treatment $\\times$ Post")
for(i in seq_len(4)) add(c("GovCS","GovTWFE","AppealCS","AppealTWFE")[i],100*x[i],"city_year_cs_twfe_main_table.tex","percentage points")
x <- values("admin_mechanism_selection_vs_quality_table.tex","Treatment $\\times$ Post",1L)
add("MeritsWin",100*x[3],"admin_mechanism_selection_vs_quality_table.tex","percentage points")
x <- values("admin_mechanism_selection_vs_quality_table.tex","Treatment $\\times$ Post",2L)
add("Withdrawal",100*x[1],"admin_mechanism_selection_vs_quality_table.tex","percentage points")
add("Termination",100*x[2],"admin_mechanism_selection_vs_quality_table.tex","percentage points")
nonlocal <- fread(file.path(tables,"h3_nonlocal_exit_interactions.csv"))
add("NonlocalExit",100*nonlocal[outcome=="exit_without_merits",estimate],"h3_nonlocal_exit_interactions.csv","percentage points")
x <- values("admin_first_stage_counsel_table.tex","Treatment $\\times$ Post")
for(i in seq_len(3)) add(c("CaseCounsel","CityCounselTWFE","CityCounselCS")[i],100*x[c(1,4,5)[i]],"admin_first_stage_counsel_table.tex","percentage points")
x <- values("firm_level_stacked_did_main_table.tex","Winner $\\times$ Post")
for(i in seq_len(3)) add(c("FirmCivilWin","FirmHearing","FirmFee")[i],if(i==2L) x[i] else 100*x[i],"firm_level_stacked_did_main_table.tex",if(i==2L) "days" else "percentage points")
add("HearingReduction",abs(x[2]),"firm_level_stacked_did_main_table.tex","days fewer")
x <- values("firm_caseload_expansion_table.tex","Winner $\\times$ Post")
add("FirmCases",x[1],"firm_caseload_expansion_table.tex")
add("FirmSize",x[3],"firm_caseload_expansion_table.tex")
add("FirmEnterprise",100*x[5],"firm_caseload_expansion_table.tex","percentage points")
x <- values("document_mechanism_pure_private_placebo_table.tex","Winner $\\times$ Post")
add("PrivateWin",100*x[3],"document_mechanism_pure_private_placebo_table.tex","percentage points")
add("PrivateFee",100*x[4],"document_mechanism_pure_private_placebo_table.tex","percentage points")
p <- fread(file.path(tables,"political_leadership_results.csv"))
political_names <- c("One", "Two", "Three", "Four", "Five", "Six", "Seven")
for(i in seq_len(nrow(p))) add(paste0("Political",political_names[i]),100*p$estimate[i],"political_leadership_results.csv","percentage points")
annual <- fread(file.path(tables,"main_hypothesis_first_four_periods.csv"))
pre <- fread(file.path(tables,"main_dynamic_joint_pretests.csv"))
add("AnnualEarlySupported",sum(annual$assessment=="DIRECTION_AND_P_SUPPORTED"),"main_hypothesis_first_four_periods.csv","observations")
add("AnnualEarlyTotal",nrow(annual),"main_hypothesis_first_four_periods.csv","observations")
add("AnnualPreRejected",sum(pre$p_value<.05,na.rm=TRUE),"main_dynamic_joint_pretests.csv","observations")
add("AnnualPreTotal",nrow(pre),"main_dynamic_joint_pretests.csv","observations")
for(item in list(c("CityN","city_year_panel.csv"),c("FirmYearN","firm_level.csv"),c("AdminN","admin_case_level.csv"),c("CivilN","document_level_winner_vs_loser.csv"),c("LawyerYearN","lawyer_position_year.csv"))) {
  d <- fread(file.path(root,"data",item[2]),select=1L)
  add(item[1],nrow(d),item[2],"observations")
}
add("CityUnits",uniqueN(fread(file.path(root,"data/city_year_panel.csv"),select=c("province","city"))),"city_year_panel.csv","observations")
add("FirmUnits",uniqueN(fread(file.path(root,"data/firm_level.csv"),select="firm_id")$firm_id),"firm_level.csv","observations")
add("LawyerUnits",uniqueN(fread(file.path(root,"data/lawyer_position_year.csv"),select="lawyer_id")$lawyer_id),"lawyer_position_year.csv","observations")
v <- rbindlist(rows)
stopifnot(all(is.finite(v$value)))
fwrite(v,file.path(tables,"result_values.csv"))
dir.create(file.path(tables,"manuscript"),showWarnings=FALSE,recursive=TRUE)
commands <- vapply(seq_len(nrow(v)),function(i) {
  display <- if(v$unit[i]=="observations") format(v$value[i],big.mark=",",scientific=FALSE,trim=TRUE) else if(v$unit[i]=="coefficient") sprintf("%.3f",v$value[i]) else sprintf("%.1f",v$value[i])
  sprintf("\\newcommand{\\Result%s}{%s}",v$name[i],display)
},character(1))
writeLines(commands,file.path(tables,"manuscript","result_values.tex"))
lines <- c("# Results summary","","Numerical prose uses the same precision as the source tables. Data provenance and scope are documented in README.","",
  "| Result | Estimate | Unit | Source |","|---|---:|---|---|",
  vapply(seq_len(nrow(v)),function(i) sprintf("| %s | %.6g | %s | %s |",v$name[i],v$value[i],v$unit[i],v$source[i]),character(1)))
writeLines(lines,file.path(tables,"results_summary.md"))
